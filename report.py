
import os
from datetime import datetime
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import inch
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Image,
    Table,
    TableStyle
)


def generate_report(image_path, disease, confidence):

    # Create reports folder
    reports_folder = "static/reports"
    os.makedirs(reports_folder, exist_ok=True)

    # Generate unique PDF filename
    filename = "CropCare_Report_" + datetime.now().strftime("%Y%m%d_%H%M%S_%f") + ".pdf"

    pdf_path = os.path.join(reports_folder, filename)

    # Create PDF document
    document = SimpleDocTemplate(
        pdf_path,
        pagesize=A4,
        rightMargin=50,
        leftMargin=50,
        topMargin=40,
        bottomMargin=40
    )

    styles = getSampleStyleSheet()

    title_style = ParagraphStyle(
        "CropCareTitle",
        parent=styles["Title"],
        textColor=colors.HexColor("#236b3b"),
        fontSize=24,
        spaceAfter=15
    )

    heading_style = ParagraphStyle(
        "CropCareHeading",
        parent=styles["Heading2"],
        textColor=colors.HexColor("#236b3b"),
        spaceBefore=12,
        spaceAfter=8
    )

    normal_style = styles["BodyText"]

    content = []

    # Title
    content.append(Paragraph("CropCare", title_style))

    content.append(
        Paragraph(
            "AI-Powered Plant Disease Detection and Advisory System",
            normal_style
        )
    )

    content.append(Spacer(1, 15))

    # Report date
    current_date = datetime.now().strftime("%d-%m-%Y %I:%M %p")

    content.append(
        Paragraph(
            f"<b>Detection Date:</b> {current_date}",
            normal_style
        )
    )

    content.append(Spacer(1, 15))

    # Uploaded plant image
    content.append(
        Paragraph("Uploaded Plant Leaf Image", heading_style)
    )

    if os.path.exists(image_path):

        leaf_image = Image(
            image_path,
            width=2.5 * inch,
            height=2.5 * inch
        )

        leaf_image.hAlign = "LEFT"
        content.append(leaf_image)

    content.append(Spacer(1, 15))

    # Disease information
    content.append(
        Paragraph("Detection Result", heading_style)
    )

    result_table = Table(
        [
            ["Disease Name", disease["name"]],
            ["AI Confidence", f"{confidence:.2f}%"]
        ],
        colWidths=[150, 300]
    )

    result_table.setStyle(
        TableStyle([
            ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#e7f2e8")),
            ("TEXTCOLOR", (0, 0), (0, -1), colors.HexColor("#236b3b")),
            ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
            ("PADDING", (0, 0), (-1, -1), 10),
            ("VALIGN", (0, 0), (-1, -1), "TOP")
        ])
    )

    content.append(result_table)

    # Symptoms
    content.append(
        Paragraph("Symptoms", heading_style)
    )

    content.append(
        Paragraph(disease["symptoms"], normal_style)
    )

    # Prevention advice
    content.append(
        Paragraph("Prevention Advice", heading_style)
    )

    content.append(
        Paragraph(disease["advice"], normal_style)
    )

    content.append(Spacer(1, 25))

    # Disclaimer
    content.append(
        Paragraph(
            "<b>Disclaimer:</b> This report is generated using an AI model. "
            "The prediction is an estimate and should not replace advice "
            "from a qualified agricultural expert.",
            normal_style
        )
    )

    content.append(Spacer(1, 20))

    content.append(
        Paragraph(
            "Generated by CropCare",
            styles["Italic"]
        )
    )

    # Generate PDF
    document.build(content)

    return filename
